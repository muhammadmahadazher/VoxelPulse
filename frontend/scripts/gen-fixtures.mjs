#!/usr/bin/env node
/** Deterministic test fixtures (§56) — small files, committed; larger
 *  fixtures stay generated-at-test-time. Usage: node scripts/gen-fixtures.mjs
 *  Writes into tests/fixtures/. Output is byte-stable across runs. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "tests", "fixtures");
mkdirSync(root, { recursive: true });

/** Same deterministic pattern as tiny.xyz: ground plane + raised box + outliers. */
function patternPoints(n) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const t = i / n;
    const x = (i % 5) * 0.5;
    const y = Math.floor(i / 5) * 0.5;
    const z = (i % 7 === 0) ? 1.25 : 0.02 * (i % 3);
    const intensity = Math.round(40 + 160 * t) / 255;
    pts.push([x, y, z, intensity]);
  }
  return pts;
}

// ---- tiny.las — v1.2, point format 0, scale 0.01, offset (1000, 2000, 100)
{
  const n = 40;
  const pts = patternPoints(n);
  const scale = [0.01, 0.01, 0.01];
  const offset = [1000, 2000, 100];
  const headerSize = 227;
  const recordLength = 20;
  const buf = Buffer.alloc(headerSize + n * recordLength);
  buf.write("LASF", 0, "ascii");
  buf.writeUInt8(1, 24);
  buf.writeUInt8(2, 25);
  buf.writeUInt32LE(headerSize, 96);
  buf.writeUInt32LE(0, 104); // VLR count
  buf.writeUInt8(0, 106); // point format 0
  buf.writeUInt16LE(recordLength, 107);
  buf.writeUInt32LE(n, 109); // legacy count
  for (let k = 0; k < 3; k++) buf.writeDoubleLE(scale[k], 131 + 8 * k);
  for (let k = 0; k < 3; k++) buf.writeDoubleLE(offset[k], 155 + 8 * k);
  const xs = pts.map((p) => p[0] * scale[0] + offset[0]);
  const ys = pts.map((p) => p[1] * scale[1] + offset[1]);
  const zs = pts.map((p) => p[2] * scale[2] + offset[2]);
  buf.writeDoubleLE(Math.min(...xs), 179);
  buf.writeDoubleLE(Math.min(...ys), 187);
  buf.writeDoubleLE(Math.min(...zs), 195);
  buf.writeDoubleLE(Math.max(...xs), 203);
  buf.writeDoubleLE(Math.max(...ys), 211);
  buf.writeDoubleLE(Math.max(...zs), 219);
  pts.forEach((p, i) => {
    const base = headerSize + i * recordLength;
    buf.writeInt32LE(Math.round((p[0] - offset[0]) / scale[0]), base);
    buf.writeInt32LE(Math.round((p[1] - offset[1]) / scale[1]), base + 4);
    buf.writeInt32LE(Math.round((p[2] - offset[2]) / scale[2]), base + 8);
    buf.writeUInt16LE(Math.round(p[3] * 65535), base + 12);
  });
  writeFileSync(join(root, "tiny.las"), buf);
}

// ---- tiny.ply — ascii, x y z intensity(float)
{
  const pts = patternPoints(25);
  const header = [
    "ply", "format ascii 1.0", "comment generated by VoxelPulse fixtures",
    "element vertex 25",
    "property float x", "property float y", "property float z", "property float intensity",
    "end_header", "",
  ].join("\n");
  const body = pts.map((p) => `${p[0]} ${p[1]} ${p[2]} ${p[3].toFixed(4)}`).join("\n") + "\n";
  writeFileSync(join(root, "tiny.ply"), header + body, "utf8");
}

// ---- tiny-binary.ply — binary_little_endian, x y z intensity(float)
{
  const pts = patternPoints(25);
  const header = [
    "ply", "format binary_little_endian 1.0",
    "element vertex 25",
    "property float x", "property float y", "property float z", "property float intensity",
    "end_header",
  ].join("\n") + "\n";
  const head = Buffer.from(header, "utf8");
  const body = Buffer.alloc(25 * 16);
  pts.forEach((p, i) => {
    body.writeFloatLE(p[0], i * 16);
    body.writeFloatLE(p[1], i * 16 + 4);
    body.writeFloatLE(p[2], i * 16 + 8);
    body.writeFloatLE(p[3], i * 16 + 12);
  });
  writeFileSync(join(root, "tiny-binary.ply"), Buffer.concat([head, body]));
}

